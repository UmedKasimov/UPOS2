from __future__ import annotations

from pathlib import Path


STATIC_DIR = Path(__file__).resolve().parent / "static"
APP_CORE_SOURCES = (
    "modal-dismiss.js",
    "lazy-datalist.js",
    "workspace-section-reset.js",
    "layout-sidebar.js",
    "workspace-module-tabs.js",
    "module-tabs-sync.js",
    "cell-title.js",
    "uz-phone.js",
    "ajax-sections.js",
    "password-toggle.js",
    "instant-navigation.js",
    "app-warmup.js",
    "messenger-notifications.js",
    "floating-phone.js",
    "amount-format.js",
    "money-auto-format.js",
    "currency-meta.js",
    "currency-select.js",
    "avatar-upload.js",
    "workspace-switcher.js",
    "device-heartbeat.js",
)


def build_app_core() -> Path:
    target = STATIC_DIR / "app-core.js"
    chunks = [
        "/* Generated by python -m upos.build_static_bundles. Do not edit directly. */\n"
    ]
    for name in APP_CORE_SOURCES:
        source = STATIC_DIR / name
        chunks.append(f"\n/* source: {name} */\n")
        chunks.append(source.read_text(encoding="utf-8").rstrip())
        chunks.append("\n")
    content = "".join(chunks)
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        target.write_text(content, encoding="utf-8", newline="\n")
    return target


def main() -> None:
    build_app_core()


if __name__ == "__main__":
    main()
